import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
const model = JSON.parse(await fs.readFile(path.join(rootDir, "project-model.json"), "utf8"));
const resourceById = new Map(model.resources.map((resource) => [resource.id, resource]));

const escapeHtml = (value = "") => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&#039;");

const phasePath = (phase) => `project/${phase.id}-${phase.title.toLowerCase().replaceAll("&", "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}.html`;
const prefixPath = (prefix, target) => `${prefix}${target}`;

function siteHeader(prefix) {
  return `
  <a class="skip-link" href="#main-content">Skip to main content</a>
  <header class="site-header">
    <div class="nav-shell">
      <a class="brand" href="${prefixPath(prefix, "index.html")}">
        <span class="brand-mark">331</span>
        <span>${escapeHtml(model.course.code)} · ${escapeHtml(model.course.name)}<small>${escapeHtml(model.project.title)}</small></span>
      </a>
      <nav class="site-nav" aria-label="Project navigation">
        <a href="${prefixPath(prefix, "project/guide.html")}">Project guide</a>
        <a href="${prefixPath(prefix, phasePath(model.phases[0]))}">Phase 1</a>
        <a href="${prefixPath(prefix, "project/assessment.html")}">Assessment</a>
      </nav>
    </div>
  </header>`;
}

function footer() {
  return `
  <footer class="footer">
    <div class="footer-shell">
      <div><strong>${escapeHtml(model.course.code)} · ${escapeHtml(model.course.name)}</strong><br>${escapeHtml(model.course.school)} · ${escapeHtml(model.course.institution)}</div>
      <div>${escapeHtml(model.course.term)} · ${escapeHtml(model.project.title)}</div>
    </div>
  </footer>`;
}

function shell({ title, description, prefix = "", body, pageClass = "" }) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="description" content="${escapeHtml(description)}">
  <title>${escapeHtml(title)} · ${escapeHtml(model.course.code)}</title>
  <link rel="stylesheet" href="${prefixPath(prefix, "styles/bus331-investment-project.css")}">
</head>
<body class="${escapeHtml(pageClass)}">
  <!-- Generated by scripts/build-investment-project.mjs from project-model.json. -->
  ${siteHeader(prefix)}
  ${body}
  ${footer()}
</body>
</html>
`.replace(/[ \t]+$/gm, "");
}

function roleBoard() {
  return `<div class="role-board">
    ${model.roles.map((role) => `<article class="role-row" data-color="${escapeHtml(role.color)}">
      <div class="role-color" aria-hidden="true"></div>
      <div class="role-name"><p class="role-tag">Committee seat</p><h3>${escapeHtml(role.title)}</h3></div>
      <div class="role-mandate">${escapeHtml(role.mandate)}</div>
    </article>`).join("\n")}
  </div>`;
}

function protocolMarkup() {
  return `<div class="protocol">
    <div>
      <p class="section-kicker">Committee operating protocol</p>
      <h2>Every phase ends with a decision</h2>
      <p class="protocol-intro">Analysis becomes committee work only when the team challenges it, votes, and records what happens next.</p>
    </div>
    <div class="protocol-steps">
      ${model.committeeProtocol.map((item) => `<article class="protocol-step"><div><h3>${escapeHtml(item.step)}</h3><p>${escapeHtml(item.description)}</p></div></article>`).join("\n")}
    </div>
  </div>`;
}

function resourceLinks(ids, prefix, { includeDescription = false } = {}) {
  return ids.map((id) => {
    const resource = resourceById.get(id);
    if (!resource) throw new Error(`Unknown resource id: ${id}`);
    return `<a class="resource-link" href="${escapeHtml(prefixPath(prefix, resource.path))}">
      <span class="resource-type">${escapeHtml(resource.type)}</span>
      <strong>${escapeHtml(resource.label)}</strong>
      ${includeDescription ? `<span>${escapeHtml(resource.description)}</span>` : ""}
    </a>`;
  }).join("\n");
}

function aiRulesMarkup() {
  return `<div class="ai-rules">
    ${model.aiRules.map((rule) => `<article class="ai-rule" data-tone="${escapeHtml(rule.tone)}">
      <p class="role-tag">${escapeHtml(rule.status)}</p>
      <h3>${escapeHtml(rule.title)}</h3>
      <p>${escapeHtml(rule.description)}</p>
    </article>`).join("\n")}
  </div>`;
}

